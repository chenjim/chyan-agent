// @vitest-environment happy-dom
import { describe, expect, it, vi } from 'vitest';

import { loginView } from './login';

function mount(onSubmit: (token: string) => void): HTMLElement {
  document.body.innerHTML = '';
  const root = document.createElement('div');
  root.innerHTML = loginView(onSubmit).html;
  document.body.appendChild(root);
  loginView(onSubmit).mounted?.(root);
  return root;
}

function submit(root: HTMLElement, token: string): void {
  (root.querySelector('#login-token') as HTMLInputElement).value = token;
  root.querySelector('form')?.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
}

describe('loginView', () => {
  it('states that the token comes from daemon startup flags, not generated by daemon', () => {
    const root = mount(() => {});
    const hint = root.querySelector('.login-hint')?.textContent ?? '';
    expect(hint).toContain('--token');
    expect(hint).toContain('CHYAN_TOKEN');
    expect(hint).not.toContain('daemon 生成的');
  });

  it('submits the trimmed token', () => {
    const onSubmit = vi.fn();
    const root = mount(onSubmit);
    submit(root, '  secret-token  ');
    expect(onSubmit).toHaveBeenCalledWith('secret-token');
  });

  it('ignores an empty token', () => {
    const onSubmit = vi.fn();
    const root = mount(onSubmit);
    submit(root, '   ');
    expect(onSubmit).not.toHaveBeenCalled();
  });
});
